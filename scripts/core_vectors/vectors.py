#!/usr/bin/env python3
"""Turns Bitcoin Core's script test vectors into cases for the `run_case` executable.

    vectors.py <script_tests.json> <script_assets_test.json> <out.jsonl>

Each output line is one verification: the spending transaction, the outputs it spends, the input
to check, the flags, and whether Bitcoin Core expects the input to be valid. `args` is the
`Case` struct of packages/core_vectors serialized as Cairo felts.

- script_tests.json (bitcoin/bitcoin, src/test/data): each test is run the way Bitcoin Core's
  script_tests.cpp runs it, in a one-input transaction spending a crediting transaction.
- script_assets_test.json (bitcoin-core/qa-assets, unit_test_data): the Taproot consensus tests
  generated by feature_taproot.py. Each entry gives a transaction, its prevouts and an input, with
  a valid witness ("success") and usually an invalid one ("failure"). Both are checked under the
  entry's own flags.
"""
import decimal
import hashlib
import json
import sys

# ------------------------------------------------------------------ transactions

def compact_size(n):
    if n < 0xFD:
        return bytes([n])
    if n <= 0xFFFF:
        return b"\xfd" + n.to_bytes(2, "little")
    if n <= 0xFFFFFFFF:
        return b"\xfe" + n.to_bytes(4, "little")
    return b"\xff" + n.to_bytes(8, "little")


def read_compact_size(b, i):
    n = b[i]
    if n < 0xFD:
        return n, i + 1
    size = {0xFD: 2, 0xFE: 4, 0xFF: 8}[n]
    return int.from_bytes(b[i + 1:i + 1 + size], "little"), i + 1 + size


def parse_tx(raw):
    i = 4
    tx = {"version": raw[0:4], "vin": [], "vout": []}
    segwit = raw[4] == 0 and raw[5] != 0
    if segwit:
        i += 2
    n, i = read_compact_size(raw, i)
    for _ in range(n):
        outpoint = raw[i:i + 36]
        i += 36
        ln, i = read_compact_size(raw, i)
        script_sig = raw[i:i + ln]
        i += ln
        sequence = raw[i:i + 4]
        i += 4
        tx["vin"].append({"outpoint": outpoint, "script_sig": script_sig, "sequence": sequence, "witness": []})
    n, i = read_compact_size(raw, i)
    for _ in range(n):
        value = raw[i:i + 8]
        i += 8
        ln, i = read_compact_size(raw, i)
        tx["vout"].append({"value": value, "script_pubkey": raw[i:i + ln]})
        i += ln
    if segwit:
        for vin in tx["vin"]:
            n, i = read_compact_size(raw, i)
            for _ in range(n):
                ln, i = read_compact_size(raw, i)
                vin["witness"].append(raw[i:i + ln])
                i += ln
    tx["locktime"] = raw[i:i + 4]
    assert i + 4 == len(raw), "trailing bytes"
    return tx


def serialize_tx(tx, with_witness=True):
    has_witness = with_witness and any(v["witness"] for v in tx["vin"])
    out = tx["version"]
    if has_witness:
        out += b"\x00\x01"
    out += compact_size(len(tx["vin"]))
    for v in tx["vin"]:
        out += v["outpoint"] + compact_size(len(v["script_sig"])) + v["script_sig"] + v["sequence"]
    out += compact_size(len(tx["vout"]))
    for o in tx["vout"]:
        out += o["value"] + compact_size(len(o["script_pubkey"])) + o["script_pubkey"]
    if has_witness:
        for v in tx["vin"]:
            out += compact_size(len(v["witness"]))
            for w in v["witness"]:
                out += compact_size(len(w)) + w
    return out + tx["locktime"]


def sha256(b):
    return hashlib.sha256(b).digest()


def txid(tx):
    """The txid in internal byte order, as it appears in an outpoint."""
    return sha256(sha256(serialize_tx(tx, with_witness=False)))


def parse_txout(raw):
    amount = int.from_bytes(raw[0:8], "little")
    ln, i = read_compact_size(raw, 8)
    assert i + ln == len(raw)
    return amount, raw[i:i + ln]


