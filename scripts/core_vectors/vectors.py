# As in core_read.cpp: every name is also accepted without its "OP_" prefix.
OPCODES = {}
for _op, _name in OPCODE_NAMES.items():
    OPCODES[_name] = _op
    OPCODES[_name[3:]] = _op


def push_data(data):
    n = len(data)
    if n < 0x4C:
        return bytes([n]) + data
    if n <= 0xFF:
        return b"\x4c" + bytes([n]) + data
    if n <= 0xFFFF:
        return b"\x4d" + n.to_bytes(2, "little") + data
    return b"\x4e" + n.to_bytes(4, "little") + data


def script_num(n):
    if n == 0:
        return b""
    negative, magnitude = n < 0, abs(n)
    out = bytearray()
    while magnitude:
        out.append(magnitude & 0xFF)
        magnitude >>= 8
    if out[-1] & 0x80:
        out.append(0x80 if negative else 0)
    elif negative:
        out[-1] |= 0x80
    return bytes(out)


def push_int(n):
    if n == 0:
        return b"\x00"
    if n == -1 or 1 <= n <= 16:
        return bytes([0x50 + n])
    return push_data(script_num(n))


def parse_script(text):
    out = b""
    for word in text.split():
        if word.isdigit() or (word.startswith("-") and len(word) > 1 and word[1:].isdigit()):
            n = int(word)
            assert -0xFFFFFFFF <= n <= 0xFFFFFFFF, word
            out += push_int(n)
        elif word.startswith("0x") and len(word) > 2:
            out += bytes.fromhex(word[2:])
        elif len(word) >= 2 and word[0] == "'" and word[-1] == "'":
            out += push_data(word[1:-1].encode())
        else:
            out += bytes([OPCODES[word]])
    return out


# ------------------------------------------------------------------ Taproot, for #TAPROOTOUTPUT#

P = 2**256 - 2**32 - 977
N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141
G = (0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798,
     0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8)
# XOnlyPubKey::NUMS_H in Bitcoin Core: a key with no known discrete logarithm.
NUMS_H = 0x50929B74C1A04954B78B4B6035E97A5E078A5A0F28EC96D547BFEE9ACE803AC0


def point_add(a, b):
    if a is None:
        return b
    if b is None:
        return a
    if a[0] == b[0] and (a[1] + b[1]) % P == 0:
        return None
    if a == b:
        lam = 3 * a[0] * a[0] * pow(2 * a[1], P - 2, P) % P
    else:
        lam = (b[1] - a[1]) * pow(b[0] - a[0], P - 2, P) % P
    x = (lam * lam - a[0] - b[0]) % P
    return x, (lam * (a[0] - x) - a[1]) % P


def point_mul(k, point):
    result = None
    while k:
        if k & 1:
            result = point_add(result, point)
        point = point_add(point, point)
        k >>= 1
    return result


def lift_x(x):
    y = pow((x * x * x + 7) % P, (P + 1) // 4, P)
    assert y * y % P == (x * x * x + 7) % P
    return x, y if y % 2 == 0 else P - y


def tagged_hash(tag, msg):
    t = sha256(tag.encode())
    return sha256(t + t + msg)


def single_leaf_taproot(script):
    """Output script and control block for a tree with one tapscript leaf, internal key NUMS_H."""
    leaf = tagged_hash("TapLeaf", b"\xc0" + compact_size(len(script)) + script)
    internal = NUMS_H.to_bytes(32, "big")
    tweak = int.from_bytes(tagged_hash("TapTweak", internal + leaf), "big")
    assert tweak < N
    q = point_add(lift_x(NUMS_H), point_mul(tweak, G))
    output = b"\x51\x20" + q[0].to_bytes(32, "big")
    control_block = bytes([0xC0 | (q[1] & 1)]) + internal
    return output, control_block


# ------------------------------------------------------------------ Shinigami flags

FLAGS = {
    "": 0, "NONE": 0, "P2SH": 0x1, "NULLDUMMY": 0x2, "DISCOURAGE_UPGRADABLE_NOPS": 0x4,
    "CHECKLOCKTIMEVERIFY": 0x8, "CHECKSEQUENCEVERIFY": 0x10, "CLEANSTACK": 0x20, "DERSIG": 0x40,
    "LOW_S": 0x80, "MINIMALDATA": 0x100, "NULLFAIL": 0x200, "SIGPUSHONLY": 0x400,
    "STRICTENC": 0x800, "WITNESS": 0x1000, "DISCOURAGE_UPGRADABLE_WITNESS_PROGRAM": 0x2000,
    "MINIMALIF": 0x4000, "WITNESS_PUBKEYTYPE": 0x8000, "TAPROOT": 0x10000,
    "DISCOURAGE_UPGRADABLE_TAPROOT_VERSION": 0x20000, "DISCOURAGE_OP_SUCCESS": 0x40000,
    "DISCOURAGE_UPGRADABLE_PUBKEYTYPE": 0x80000, "CONST_SCRIPTCODE": 0x100000,
}


def parse_flags(text):
    value = 0
    for name in text.split(","):
        value |= FLAGS[name]
    return value


# ------------------------------------------------------------------ Cairo serialization

FIELD_PRIME = 2**251 + 17 * 2**192 + 1


def ser_bytes(b):
    words = [b[i:i + 31] for i in range(0, len(b) - len(b) % 31, 31)]
    pending = b[len(words) * 31:]
    return [len(words)] + [int.from_bytes(w, "big") for w in words] + [int.from_bytes(pending, "big"), len(pending)]


def case_args(transaction, prevouts, index, flags):
    felts = ser_bytes(transaction) + [len(prevouts)]
    for amount, script in prevouts:
        felts += [amount % FIELD_PRIME] + ser_bytes(script)
    return [hex(x) for x in felts + [index, flags]]


# ------------------------------------------------------------------ the two vector files

def script_tests(path):
    for number, test in enumerate(json.load(open(path))):
        if not (isinstance(test, list) and len(test) >= 4):
            continue
        witness, amount, script = [], 0, b""
        pos = 0
        if isinstance(test[0], list):
            for element in test[0][:-1]:
                if element.startswith("#SCRIPT#"):
                    script = parse_script(element[len("#SCRIPT#"):])
                    witness.append(script)
                elif element == "#CONTROLBLOCK#":
                    witness.append(single_leaf_taproot(script)[1])
                else:
                    witness.append(bytes.fromhex(element))
            amount = int(decimal.Decimal(str(test[0][-1])) * 100000000)
            pos = 1
        script_sig_text, script_pubkey_text, flags_text, expected = test[pos:pos + 4]
        comment = test[pos + 4] if len(test) > pos + 4 else ""
        script_sig = parse_script(script_sig_text)
        if script_pubkey_text == "0x51 0x20 #TAPROOTOUTPUT#":
            script_pubkey = single_leaf_taproot(script)[0]
        else:
            script_pubkey = parse_script(script_pubkey_text)

        # BuildCreditingTransaction and BuildSpendingTransaction in Bitcoin Core.
        credit = {
            "version": (1).to_bytes(4, "little"),
            "vin": [{"outpoint": b"\x00" * 32 + b"\xff" * 4, "script_sig": b"\x00\x00",
                     "sequence": b"\xff" * 4, "witness": []}],
            "vout": [{"value": amount.to_bytes(8, "little"), "script_pubkey": script_pubkey}],
            "locktime": b"\x00" * 4,
        }
        spend = {
            "version": (1).to_bytes(4, "little"),
            "vin": [{"outpoint": txid(credit) + b"\x00" * 4, "script_sig": script_sig,
                     "sequence": b"\xff" * 4, "witness": witness}],
            "vout": [{"value": amount.to_bytes(8, "little"), "script_pubkey": b""}],
            "locktime": b"\x00" * 4,
        }
        yield {
            "id": f"script_tests/{number}",
            "source": "script_tests",
            "category": expected,
            "flags": flags_text,
            "expect_valid": expected == "OK",
            "description": f"{script_sig_text} | {script_pubkey_text} | {flags_text} | {expected} | {comment}"[:300],
            "args": case_args(serialize_tx(spend), [(amount, script_pubkey)], 0, parse_flags(flags_text)),
        }


def script_assets(path):
    raw = open(path).read().strip().rstrip(",")
    if not raw.startswith("["):
        raw = "[" + raw + "]"
    for number, test in enumerate(json.loads(raw)):
        tx = parse_tx(bytes.fromhex(test["tx"]))
        prevouts = [parse_txout(bytes.fromhex(p)) for p in test["prevouts"]]
        assert len(prevouts) == len(tx["vin"])
        index, flags = test["index"], parse_flags(test["flags"])
        for part, expect_valid in (("success", True), ("failure", False)):
            if part not in test:
                continue
            tx["vin"][index]["script_sig"] = bytes.fromhex(test[part]["scriptSig"])
            tx["vin"][index]["witness"] = [bytes.fromhex(w) for w in test[part]["witness"]]
            yield {
                "id": f"script_assets/{number}/{part}",
                "source": "script_assets",
                "category": test["comment"].split("/")[0],
                "flags": test["flags"],
                "expect_valid": expect_valid,
                "description": f"{test['comment']} | {test['flags']}" + (" | final" if test.get("final") else ""),
                "args": case_args(serialize_tx(tx), prevouts, index, flags),
            }


def main():
    script_tests_path, assets_path, out_path = sys.argv[1:4]
    count = 0
    with open(out_path, "w") as out:
        for case in list(script_tests(script_tests_path)) + list(script_assets(assets_path)):
            out.write(json.dumps(case) + "\n")
            count += 1
    print(f"wrote {count} cases to {out_path}")


if __name__ == "__main__":
    main()
